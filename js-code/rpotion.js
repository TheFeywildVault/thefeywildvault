//RARITY

function getColumnForLevel(level) {
    if (level >= 1 && level <= 4) return 0;
    if (level >= 5 && level <= 10) return 1;
    if (level >= 11 && level <= 16) return 2;
    if (level >= 17 && level <= 20) return 3;
}

function getRarity(level, roll) {
    // Get all rarity checkboxes
    const rarityCheckboxes = document.querySelectorAll("#rarityDropdown .rarity");

    // Get checked rarities
    const selectedRarities = Array.from(rarityCheckboxes)
        .filter(box => box.checked)
        .map(box => box.value);

    /*
    CASES:
    - 0 checked → use default level-based rarity
    - 1-5 checked → randomly choose from selected rarities
    */
    if (selectedRarities.length > 0) {
        const randomIndex = Math.floor(Math.random() * selectedRarities.length);
        return selectedRarities[randomIndex];
    }

    // EXISTING LEVEL-BASED RARITY LOGIC
    const rarityTable = [
        [3, 3, 3, 3, 4], // Level 1-4
        [3, 4, 4, 4, 5], // Level 5-10
        [4, 4, 5, 5, 6], // Level 11-16
        [5, 5, 5, 6, 7], // Level 17-20
    ];

    const rarityLabels = [
        "Common",
        "Uncommon",
        "Rare",
        "Very Rare",
        "Legendary"
    ];

    const column = getColumnForLevel(level);

    // Ensure roll produces a valid index
    const index = Math.min(Math.floor(roll / 2), 4);

    const rarity = rarityTable[column][index];

    return rarityLabels[rarity - 3];
}

