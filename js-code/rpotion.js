// FINAL RANDOM ITEM OUTPUT
function generateRandomPotions() {
  console.log("Generate Potions clicked");

  const runCountInput = document.getElementById("runCount");
  const levelInput = document.getElementById("level");
  const resultDiv = document.getElementById("result");

  if (!runCountInput || !levelInput || !resultDiv) {
    console.error("Missing required HTML element:", {
      runCountInput,
      levelInput,
      resultDiv
    });
    return;
  }

  const runCount = parseInt(runCountInput.value);
  const level = parseInt(levelInput.value);

  resultDiv.innerHTML = "";

  const placeholder = document.getElementById("placeholder-text");
  if (placeholder) placeholder.remove();

  const filteredItems = filterRandomPotionItemTable();

  console.log("Filtered potion items:", filteredItems);

  if (!filteredItems || filteredItems.length === 0) {
    resultDiv.innerHTML = "<p>No matching potions found.</p>";
    return;
  }

  for (let i = 0; i < runCount; i++) {
    const roll = Math.floor(Math.random() * 10) + 1;
    const rarity = getRarity(level, roll);

    const rarityMapping = {
      "Common": "common",
      "Uncommon": "uncommon",
      "Rare": "rare",
      "Very Rare": "veryrare",
      "Legendary": "legendary"
    };

    const rarityKey = rarityMapping[rarity];

    let validItems = filteredItems.filter(item => {
      return item[rarityKey] && item[rarityKey].trim() !== "";
    });

    if (validItems.length === 0) {
      console.warn(`No ${rarity} potions found. Falling back to all filtered items.`);
      validItems = filteredItems;
    }

    const item = validItems[Math.floor(Math.random() * validItems.length)];
    const effectResult = getPotionEffect(item, rarity);

    const { damageType, flavor, offlavor } = getDamageTypeAndFlavor();
    const tag = item.type;

    let finalEffect = effectResult.effect;

    if (!finalEffect || finalEffect.trim() === "") {
      const availableRarityKey = ["common", "uncommon", "rare", "veryrare", "legendary"]
        .find(key => item[key] && item[key].trim() !== "");

      finalEffect = availableRarityKey
        ? item[availableRarityKey]
        : "<i>No effect found for this potion.</i>";
    }

    finalEffect = finalEffect
      .replace(/{element}/g, damageType)
      .replace(/{flavor}/g, flavor)
      .replace(/{of-flavor}/g, offlavor)
      .replace(/{tag}/g, tag);

    const finalname = item.effectname
      .replace(/{element}/g, damageType)
      .replace(/{flavor}/g, flavor)
      .replace(/{of-flavor}/g, offlavor)
      .replace(/{tag}/g, tag);

    const finalcost = item.cost && item.cost.trim() !== ""
      ? item.cost
      : getCost(rarity);

    const applicationText = item.application && item.application.trim() !== ""
      ? ` - ${item.application}`
      : "";

    const outputBox = document.createElement("div");
    outputBox.classList.add("output-box", "item-result");

    outputBox.innerHTML = `
      <div class="relative p-4 rounded">
        <div class="absolute top-1 right-2 flex flex-col-reverse gap-1 sm:flex-row sm:items-center sm:gap-2">
          <button class="aadd-button h-8 text-white bg-gray-700 rounded hover:bg-gray-900 transition flex items-center justify-center font-bold"
            onclick="handleShareButton(this)">
            <span class="inline sm:hidden">&gt;</span>
            <span class="hidden w-16 sm:inline">Share</span>
          </button>

          <button class="aadd-button w-8 h-8 text-white bg-gray-700 rounded hover:bg-gray-900 transition flex items-center justify-center font-bold"
            onclick="handleSaveButton(this)">
            +
          </button>
        </div>

        <div class="popup-message hidden absolute top-12 right-4 bg-gray-500/90 text-white text-sm px-3 py-1 rounded shadow z-20">
          Item Saved to Inventory
        </div>

        <div class="rarity ${rarity}">${finalname}</div>

        <p class="output-line italic">
          ${item.type}${applicationText} - ${rarity}
        </p>

        <p class="output-line effect">
          ${finalEffect}
        </p>

        <p class="output-line">Cost: ${finalcost} gp</p>

        ${(effectResult.patreon || effectResult.inspiration)
          ? `<p class="italic">
              ${effectResult.patreon ? `Patreon: ${effectResult.patreon}` : ''}
              ${effectResult.patreon && effectResult.inspiration ? ' - ' : ''}
              ${effectResult.inspiration ? `Inspiration: ${effectResult.inspiration}` : ''}
            </p>`
          : ''
        }

        ${effectResult.flavor ? `<p class="italic">Flavor: ${effectResult.flavor}</p>` : ''}
      </div>
    `;

    resultDiv.appendChild(outputBox);
  }
}

