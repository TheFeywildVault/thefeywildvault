function getPotionEffect(item, rarity) {
  const rarityMapping = {
    "Common": "common",
    "Uncommon": "uncommon",
    "Rare": "rare",
    "Very Rare": "veryrare",
    "Legendary": "legendary"
  };

  const rarityKey = rarityMapping[rarity];

  return {
    effect: item[rarityKey],
    modifier: item.effectname,
    patreon: item.patreon,
    cost: item.cost,
    inspiration: item.inspiration,
    flavor: item.flavor
  };
}

// Function to filter RandomPotionItemTable based on selected items
function filterRandomPotionItemTable() {
  const selectedTypes = Array.from(
    document.querySelectorAll("#potionTypeDropdown .dropdown-checkbox.pcat:checked")
  ).map(cb => cb.value);

  // If no type is selected, allow all potion types
  if (selectedTypes.length === 0) {
    return RandomPotionItemTable;
  }

  return RandomPotionItemTable.filter(item => selectedTypes.includes(item.type));
}

